assert.equal(field.value,'22222222-2222-4222-8222-222222222222');
assert.equal(form.dataset.restoredReceipt,undefined);
assert.equal(form.dataset.intakeId,undefined);
assert.equal(saved,1,'current fields are saved with the new receipt');
