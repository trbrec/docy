const assert=require('node:assert/strict'),vm=require('node:vm'),fs=require('node:fs');
const src=fs.readFileSync('assets/js/trb-release-upload.js','utf8');
const helper=src.slice(src.indexOf('function rotateCompletedReceipt('),src.indexOf('\nfunction receiveIntake('));
const field={value:'11111111-1111-1111-1111-111111111111'};
const form={dataset:{restoredReceipt:field.value,intakeId:'123'},querySelector:()=>field};
let saved=0;
const context={form,crypto:{randomUUID:()=> '22222222-2222-4222-8222-222222222222'},saveDraft:()=>{saved++;}};
vm.createContext(context);vm.runInContext(helper+';result=rotateCompletedReceipt;',context);
assert.equal(context.result(form,{status:'invalid_genres'}),false);
assert.equal(field.value,'11111111-1111-1111-1111-111111111111');
