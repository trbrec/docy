const assert = require('node:assert/strict');
const { buildOptions } = require('./qa-http-browser-relay.cjs');
const packet = { url: 'https://artist.trbrec.com/trb-audit-http-' + 'a'.repeat(24) + '/index.php', headers: [], fields: null };
assert.deepEqual(buildOptions(packet).headers, {});
const multipart = buildOptions({ ...packet, fields: { city: 'Tunisi', 'photo[0]': { filename: 'fixture.png', mime: 'image/png', base64: 'AAECAw==' } } });
assert.equal(multipart.multipart.city, 'Tunisi');
assert.deepEqual(multipart.multipart['photo[0]'].buffer, Buffer.from([0, 1, 2, 3]));
assert.equal(multipart.maxRedirects, 0);
assert.throws(() => buildOptions({ ...packet, url: 'https://example.com/private' }), /destination/);
assert.throws(() => buildOptions({ ...packet, headers: { Authorization: 'secret' } }), /header/);
assert.throws(() => buildOptions({ ...packet, fields: { photo: { filename: '../outside', mime: 'image/png', base64: '' } } }), /upload/);
console.log('External browser destination confinement, allowed headers, multipart bytes and redirect refusal passed.');
